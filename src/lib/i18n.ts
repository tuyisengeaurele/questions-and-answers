export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const text = (lang === "rw" ? rw : en)[key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : text;
}

type PluralBase = { [K in Key]: K extends `${infer B}_one` ? B : never }[Key];

/** Picks `<base>_one` for 1 and `<base>_other` for everything else. */
export function translatePlural(lang: Lang, base: PluralBase, n: number, vars?: Vars): string {
  return translate(lang, `${base}_${n === 1 ? "one" : "other"}` as Key, { n, ...vars });
}
